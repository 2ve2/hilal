/**
 * Generates src/core/umalqura-data.ts from the Umm al-Qura calendar built
 * into Node's ICU (`Intl.DateTimeFormat` with `ca-islamic-umalqura`).
 *
 * The runtime never touches `Intl` calendars (Hermes support differs
 * between platforms and versions); it only reads the generated table.
 *
 * Usage: yarn generate:umalqura
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';

const MIN_YEAR = 1356;
const MAX_YEAR = 1500;
const MS_PER_DAY = 86_400_000;
const OUTPUT = resolve(import.meta.dirname, '../src/core/umalqura-data.ts');

const formatter = new Intl.DateTimeFormat('en-u-ca-islamic-umalqura', {
  year: 'numeric',
  month: 'numeric',
  day: 'numeric',
  timeZone: 'UTC',
});

if (formatter.resolvedOptions().calendar !== 'islamic-umalqura') {
  throw new Error(
    'This Node.js build has no islamic-umalqura calendar. Use an official ' +
      'Node.js build with full ICU.'
  );
}

type Hijri = { year: number; month: number; day: number };

function hijriOfEpochDay(epochDay: number): Hijri {
  const parts = formatter.formatToParts(new Date(epochDay * MS_PER_DAY));
  const get = (type: Intl.DateTimeFormatPartTypes): number => {
    const part = parts.find((p) => p.type === type);
    if (!part) {
      throw new Error(`ICU returned no ${type} part`);
    }
    return Number.parseInt(part.value, 10);
  };
  return {
    year: get('year'),
    month: get('month'),
    day: get('day'),
  };
}

// Start a little before 1 Muharram 1356 (14 March 1937) and walk forward
// one day at a time, recording the first day of every Hijri month.
let epochDay = Math.floor(Date.UTC(1937, 0, 1) / MS_PER_DAY);
const monthStarts: number[] = [];
let expectedYear = MIN_YEAR;
let expectedMonth = 1;

for (;;) {
  const h = hijriOfEpochDay(epochDay);
  if (h.day === 1 && h.year === expectedYear && h.month === expectedMonth) {
    monthStarts.push(epochDay);
    if (expectedYear > MAX_YEAR) {
      break; // 1 Muharram of MAX_YEAR + 1 closes the last month.
    }
    expectedMonth += 1;
    if (expectedMonth > 12) {
      expectedMonth = 1;
      expectedYear += 1;
    }
  } else if (h.day === 1 && h.year >= MIN_YEAR) {
    throw new Error(
      `Unexpected month start ${h.year}-${h.month} at epoch day ${epochDay}`
    );
  }
  epochDay += 1;
}

// One number per Hijri year: bit (month - 1) is set when the month has
// 30 days, clear when it has 29.
const yearMasks: number[] = [];
for (let year = MIN_YEAR; year <= MAX_YEAR; year++) {
  let mask = 0;
  for (let month = 1; month <= 12; month++) {
    const index = (year - MIN_YEAR) * 12 + (month - 1);
    const length = monthStarts[index + 1]! - monthStarts[index]!;
    if (length !== 29 && length !== 30) {
      throw new Error(`Month ${year}-${month} has ${length} days`);
    }
    if (length === 30) {
      // eslint-disable-next-line no-bitwise -- the table is a bit mask
      mask |= 1 << (month - 1);
    }
  }
  yearMasks.push(mask);
}

const output = `// GENERATED FILE - DO NOT EDIT BY HAND.
// Generated by scripts/generate-umalqura-table.ts from Node's built-in ICU
// (${process.version}, ICU ${process.versions.icu}). Run \`yarn generate:umalqura\` to rebuild.

/** First Hijri year in the table. */
export const UMALQURA_MIN_YEAR = ${MIN_YEAR};

/** Last Hijri year in the table. */
export const UMALQURA_MAX_YEAR = ${MAX_YEAR};

/**
 * Days since 1970-01-01 (in the proleptic Gregorian calendar) of
 * 1 Muharram ${MIN_YEAR}.
 */
export const UMALQURA_START_EPOCH_DAY = ${monthStarts[0]};

/**
 * One entry per Hijri year from ${MIN_YEAR} to ${MAX_YEAR}. Bit (month - 1) is
 * set when that month has 30 days and clear when it has 29.
 */
export const UMALQURA_MONTH_LENGTH_MASKS: readonly number[] = [
  ${yearMasks.join(', ')}
];
`;

mkdirSync(dirname(OUTPUT), { recursive: true });
writeFileSync(OUTPUT, output);
console.log(
  `Wrote ${yearMasks.length} years (${monthStarts.length - 1} months) to ${OUTPUT}`
);
